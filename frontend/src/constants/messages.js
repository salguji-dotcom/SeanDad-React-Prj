/** 메시지 문구. {0}, {1} 자리에 args 를 넣습니다. */
export function msg(code, ...args) {
  const text = MESSAGES[code] ?? code;
  return text.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}
